-- =============================================================================
-- 017 - Propuestas de siguiente paso (AGENTE-AS-02)
-- =============================================================================
-- Idempotente. Rollback: 017-propuestas.rollback.sql
--
-- Quirqui propone, sin que se lo pidan, el siguiente paso en la pantalla donde
-- esta el usuario: un articulo bajo el punto de pedido, un lote por vencer,
-- una certificacion de herramienta que vence. Las arma con REGLAS sobre los
-- datos de las tools (agente/sugerencias.py), no con el modelo: son
-- inmediatas, no gastan tokens, y cada cifra viene de una tool (R4).
--
-- El usuario la ve ("como hacerlo") o la descarta. Una descartada no se
-- vuelve a proponer por unos dias (AGENTE_SUGERENCIA_SILENCIO_DIAS): sin eso,
-- Quirqui insistiria con lo mismo cada vez que se abre el panel.
--
-- Las propuestas son de la empresa (RLS) y de un usuario: lo que uno descarta
-- no se le esconde a otro.
-- =============================================================================

\set ON_ERROR_STOP on

CREATE TABLE IF NOT EXISTS agente.propuesta (
    propuesta_id  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empr_id       integer     NOT NULL,
    usuario       text        NOT NULL,
    clave         text        NOT NULL,
    tipo          text        NOT NULL,
    pantalla      text,
    titulo        text        NOT NULL,
    detalle       text        NOT NULL,
    accion        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    estado        text        NOT NULL DEFAULT 'pendiente',
    fec_alta      timestamptz NOT NULL DEFAULT now(),
    fec_respuesta timestamptz,
    CONSTRAINT propuesta_tipo_ck   CHECK (tipo IN ('stock_bajo', 'lote_vencido', 'lote_critico',
                                                  'certificacion_por_vencer')),
    CONSTRAINT propuesta_estado_ck CHECK (estado IN ('pendiente', 'aceptada', 'descartada')),
    CONSTRAINT propuesta_respuesta_ck CHECK ((estado = 'pendiente') = (fec_respuesta IS NULL))
);

COMMENT ON TABLE  agente.propuesta       IS 'Siguiente paso que Quirqui le propuso a un usuario, y que hizo con el (AGENTE-AS-02).';
COMMENT ON COLUMN agente.propuesta.clave IS 'Que se propuso, para no repetirlo: tipo + entidad (ej. stock_bajo:5).';

-- Una sola propuesta pendiente por usuario y cosa.
CREATE UNIQUE INDEX IF NOT EXISTS propuesta_pendiente_uk
    ON agente.propuesta (empr_id, usuario, clave) WHERE estado = 'pendiente';
CREATE INDEX IF NOT EXISTS propuesta_respuesta_ix
    ON agente.propuesta (empr_id, usuario, clave, fec_respuesta DESC) WHERE estado <> 'pendiente';

ALTER TABLE agente.propuesta ENABLE ROW LEVEL SECURITY;
ALTER TABLE agente.propuesta FORCE  ROW LEVEL SECURITY;

DROP POLICY IF EXISTS propuesta_aislamiento_empresa ON agente.propuesta;
CREATE POLICY propuesta_aislamiento_empresa ON agente.propuesta
    USING (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer)
    WITH CHECK (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer);

REVOKE ALL ON agente.propuesta FROM agente_app;
GRANT SELECT, INSERT, UPDATE ON agente.propuesta TO agente_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON agente.propuesta TO agente_curador;

