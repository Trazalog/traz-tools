-- =============================================================================
-- 019 - Contrato Kuntur <-> Quirqui: mediciones y avances (AGENTE-AS-04)
-- =============================================================================
-- Idempotente. Rollback: 019-contrato-coach.rollback.sql
--
-- El Coach y el Asistente NO conversan: intercambian DATOS por estas tablas
-- (AGENTES_TRAZALOG_ARQUITECTURA_TECNICA.md, "Contrato Kuntur <-> Quirqui").
--
--   medicion_pedida     Kuntur pide medir algo (un indicador, sobre una
--                       actividad, un equipo o una persona), cada cuanto y
--                       hasta cuando, y para que plan.
--   medicion_resultado  Quirqui (un job) deja el valor medido, con la tool de
--                       la que salio.
--   avance_plan         Quirqui informa como van las tareas de un plan.
--
-- R3 POR CONSTRUCCION: ninguna de estas tablas tiene un campo de texto libre
-- donde pueda viajar lo que conversaron el usuario y el agente. Los valores
-- son numeros, estados, fechas e ids; el `detalle` es JSON con lo que
-- devolvio una tool. El job de mediciones no lee agente.interaccion.
--
-- R11: el administrador ve y cancela lo pedido; la persona medida no ve nada
-- (lo filtra la API, que es por donde se leen).
--
-- ESTADO: solo el esquema. El job que ejecuta las mediciones necesita las
-- tools de KPI (doc/agente/analisis-impacto-kpi-objetivos.md) y las del
-- modulo de tareas; los planes de accion, el estado "propuesta" de TAR.
-- =============================================================================

\set ON_ERROR_STOP on

CREATE TABLE IF NOT EXISTS agente.medicion_pedida (
    medicion_id   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empr_id       integer     NOT NULL,
    indicador     text        NOT NULL,   -- nombre del KPI o de la tool de lectura
    parametros    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    alcance       text        NOT NULL,
    alcance_id    text,                   -- el equipo o el usuario, si el alcance no es 'actividad'
    frecuencia    text        NOT NULL,
    desde         date        NOT NULL DEFAULT current_date,
    hasta         date        NOT NULL,
    petr_id       integer,                -- el pedido de trabajo del plan (ADR-A9)
    estado        text        NOT NULL DEFAULT 'activa',
    pedida_por    text        NOT NULL DEFAULT 'kuntur',
    fec_alta      timestamptz NOT NULL DEFAULT now(),
    fec_mod       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT medicion_indicador_ck  CHECK (indicador ~ '^[a-z][a-z0-9_]{2,60}$'),
    CONSTRAINT medicion_alcance_ck    CHECK (alcance IN ('actividad', 'equipo', 'persona')),
    CONSTRAINT medicion_alcance_id_ck CHECK ((alcance = 'actividad') = (alcance_id IS NULL)),
    CONSTRAINT medicion_frecuencia_ck CHECK (frecuencia IN ('diaria', 'semanal', 'mensual')),
    CONSTRAINT medicion_estado_ck     CHECK (estado IN ('activa', 'cancelada', 'vencida')),
    CONSTRAINT medicion_vigencia_ck   CHECK (hasta >= desde)
);

CREATE TABLE IF NOT EXISTS agente.medicion_resultado (
    resultado_id  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicion_id   bigint      NOT NULL REFERENCES agente.medicion_pedida(medicion_id) ON DELETE CASCADE,
    empr_id       integer     NOT NULL,
    fecha         date        NOT NULL,
    valor         numeric,
    detalle       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    tool          text        NOT NULL,   -- de donde salio el valor (R4)
    fec_alta      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT medicion_resultado_uk UNIQUE (medicion_id, fecha)
);

CREATE TABLE IF NOT EXISTS agente.avance_plan (
    avance_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empr_id       integer     NOT NULL,
    petr_id       integer     NOT NULL,
    tarea_id      integer     NOT NULL,
    estado        text        NOT NULL,
    fec_plan      date,
    fec_real      date,
    responsable   text,
    resultado     text,
    fec_alta      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT avance_estado_ck    CHECK (estado IN ('propuesta', 'creada', 'planificada', 'iniciada',
                                                     'finalizada', 'eliminada')),
    -- `resultado` es un estado corto, no texto libre (R3).
    CONSTRAINT avance_resultado_ck CHECK (resultado IS NULL OR resultado IN ('en_plazo', 'atrasada', 'cancelada'))
);
CREATE INDEX IF NOT EXISTS avance_plan_ix ON agente.avance_plan (empr_id, petr_id, fec_alta DESC);

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['medicion_pedida', 'medicion_resultado', 'avance_plan'] LOOP
        EXECUTE format('ALTER TABLE agente.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE agente.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON agente.%I', t || '_aislamiento', t);
        EXECUTE format(
            'CREATE POLICY %I ON agente.%I '
            'USING (empr_id = NULLIF(current_setting(''agente.empr_id'', true), '''')::integer) '
            'WITH CHECK (empr_id = NULLIF(current_setting(''agente.empr_id'', true), '''')::integer)',
            t || '_aislamiento', t);
        EXECUTE format('REVOKE ALL ON agente.%I FROM agente_app', t);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON agente.%I TO agente_app', t);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON agente.%I TO agente_curador', t);
    END LOOP;
END
$$;

COMMENT ON TABLE agente.medicion_pedida    IS 'Lo que Kuntur le pide medir a Quirqui (AS-04). Sin texto libre: R3.';
COMMENT ON TABLE agente.medicion_resultado IS 'El valor medido, con la tool de la que salio (R4). Sin texto libre: R3.';
COMMENT ON TABLE agente.avance_plan        IS 'Como van las tareas de un plan de accion (AS-04). Sin texto libre: R3.';

