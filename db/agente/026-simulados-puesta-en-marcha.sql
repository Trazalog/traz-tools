\set ON_ERROR_STOP on

CREATE TABLE IF NOT EXISTS agente.simulacion (
    sim_id    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empr_id   integer     NOT NULL,
    servicio  text        NOT NULL,   -- la tool que lo grabo
    entidad   text        NOT NULL,   -- man.sector, dnato.menu_rol, ...
    clave     text,                   -- para las que reemplazan (un rol por usuario...)
    datos     jsonb       NOT NULL,
    fec_alta  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS simulacion_empresa_ix ON agente.simulacion (empr_id, entidad);

COMMENT ON TABLE agente.simulacion IS
    'Lo que graban los servicios SIMULADOS de la puesta en marcha (Mantenimiento con la interfaz de '
    'develop-v3, Dnato v3 en diseno). Deuda tecnica: se reemplaza por los servicios reales.';

ALTER TABLE agente.simulacion ENABLE ROW LEVEL SECURITY;
ALTER TABLE agente.simulacion FORCE  ROW LEVEL SECURITY;
DROP POLICY IF EXISTS simulacion_aislamiento ON agente.simulacion;
CREATE POLICY simulacion_aislamiento ON agente.simulacion
    USING (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer)
    WITH CHECK (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer);
GRANT SELECT, INSERT, DELETE ON agente.simulacion TO agente_app;
GRANT SELECT ON agente.simulacion TO agente_curador;

