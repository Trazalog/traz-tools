VALUES
    ('man_alta_sector',             'man',   'configuracion', 'medio', false, 'Alta de un sector de Mantenimiento (simulado)'),
    ('man_alta_area',               'man',   'configuracion', 'medio', false, 'Alta de un área de Mantenimiento (simulado)'),
    ('man_alta_proceso',            'man',   'configuracion', 'medio', false, 'Alta de un proceso de Mantenimiento (simulado)'),
    ('man_alta_criticidad',         'man',   'configuracion', 'medio', false, 'Alta de una criticidad de equipos (simulado)'),
    ('man_alta_grupo',              'man',   'configuracion', 'medio', false, 'Alta de un grupo de equipos (simulado)'),
    ('man_alta_marca',              'man',   'configuracion', 'medio', false, 'Alta de una marca de equipos (simulado)'),
