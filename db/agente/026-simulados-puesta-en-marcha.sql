--     MANDataService de develop-v3. Los equipos van en MariaDB (AssetPlanner).
--   * Dnato v3 (en diseno): funcionalidades, menu por rol, rol por usuario y
--     administradores de la empresa.
--
-- Lo que "graban" queda en agente.simulacion. DEUDA TECNICA: reemplazarlas por
-- los servicios reales (ver STATE.md). Para eso: borrar la fila de la tool de
-- este catalogo SOLO si el nombre cambia; si no, publicarla en el gateway con
-- el mismo nombre y sacarla de SERVICIOS en agente/simulados.py.
