ON CONFLICT (nombre) DO UPDATE SET
    modulo      = EXCLUDED.modulo,
    clase       = EXCLUDED.clase,
    riesgo      = EXCLUDED.riesgo,
    reversible  = EXCLUDED.reversible,
    descripcion = EXCLUDED.descripcion,
    fec_mod     = now();

-- Kuntur: las de lectura por patron, las de configuracion una por una (ADR-A12).
UPDATE agente.agente
   SET tools_permitidas = CASE WHEN 'dnato_get_*' = ANY (tools_permitidas) THEN tools_permitidas
                               ELSE tools_permitidas || 'dnato_get_*'::text END,
       tools_configuracion = ARRAY(SELECT DISTINCT unnest(tools_configuracion || ARRAY[
           'man_alta_sector', 'man_alta_area', 'man_alta_proceso', 'man_alta_criticidad',
           'man_alta_grupo', 'man_alta_marca', 'man_alta_equipo',
           'dnato_activar_funcionalidad', 'dnato_asignar_menu_rol', 'dnato_asignar_rol_usuario']) ORDER BY 1),
       fec_mod = now()
 WHERE clave = 'kuntur';

