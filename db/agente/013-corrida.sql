-- =============================================================================
-- 013 - Corrida auditable (R8) y aislamiento de interaccion/feedback
-- =============================================================================
-- Idempotente. Rollback: 013-corrida.rollback.sql
--
-- R8 (AGENTES_TRAZALOG_ARQUITECTURA_TECNICA.md): cada corrida queda registrada
-- --agente, disparador, entradas, tools llamadas con lo que devolvieron,
-- salida, costo, controles aplicados e incidentes-- y se puede reconstruir que
-- dato y que regla produjeron cada salida.
--
-- Tres cosas:
--
-- 1. agente.interaccion suma columnas: que agente respondio, que lo disparo,
--    cuanto costo, que controles se aplicaron y que incidentes hubo.
--
-- 2. agente.tool_llamada: una fila por tool llamada en la corrida, con EL
--    CONTENIDO QUE VIO EL MODELO (no la respuesta cruda completa: lo que se le
--    paso, ya truncado). Es lo que necesita el guardian de cifras de R4: una
--    cifra de la respuesta tiene que estar en algo que el modelo efectivamente
--    leyo.
--
-- 3. RLS en interaccion, feedback y tool_llamada. HALLAZGO del 2026-10-27:
--    interaccion y feedback no tenian RLS desde 005, aunque guardan las
--    preguntas y respuestas de cada empresa -- con datos que vinieron de sus
--    tools. Los protegia solo el WHERE empr_id del codigo. memoria,
--    notificacion y destinatario_alerta si lo tenian. Se aplica la misma
--    policy que memoria (R7). Todos los que escriben o leen estas tablas desde
--    el codigo ya fijan agente.empr_id antes: el orquestador, /feedback y
--    /admin/feedback.
-- =============================================================================

\set ON_ERROR_STOP on

-- -----------------------------------------------------------------------------
-- 1. Columnas nuevas de la corrida
-- -----------------------------------------------------------------------------
ALTER TABLE agente.interaccion
    ADD COLUMN IF NOT EXISTS agente      text REFERENCES agente.agente(clave),
    ADD COLUMN IF NOT EXISTS disparador  text NOT NULL DEFAULT 'consulta',
    ADD COLUMN IF NOT EXISTS costo_usd   numeric(12, 6),
    ADD COLUMN IF NOT EXISTS controles   jsonb NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS incidentes  jsonb NOT NULL DEFAULT '[]'::jsonb;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'interaccion_disparador_ck') THEN
        ALTER TABLE agente.interaccion ADD CONSTRAINT interaccion_disparador_ck
            CHECK (disparador IN (
                'consulta', 'apertura_pantalla', 'evento_operativo', 'medicion_pedida',
                'primer_ingreso_admin', 'cambio_contexto', 'desvio_kpi', 'cierre_medicion',
                'sesion_experto'
            ));
    END IF;
END
$$;

COMMENT ON COLUMN agente.interaccion.agente     IS 'Clave del agente que respondio (agente.agente). NULL en las corridas anteriores a 013.';
COMMENT ON COLUMN agente.interaccion.disparador IS 'Que puso en marcha la corrida: una consulta, un evento operativo, un desvio de KPI...';
COMMENT ON COLUMN agente.interaccion.costo_usd  IS 'Costo de la corrida segun OpenRouter (usage.cost). NULL si el proveedor no lo informo.';
COMMENT ON COLUMN agente.interaccion.controles  IS 'Controles aplicados y su resultado, ej. [{"control":"lista_blanca","ofrecidas":23,"bloqueadas":0}].';
COMMENT ON COLUMN agente.interaccion.incidentes IS 'Lo que hay que revisar: tools bloqueadas, cifras sin fuente (R4)... Vacio = corrida limpia.';

CREATE INDEX IF NOT EXISTS interaccion_agente_fecha_ix ON agente.interaccion (agente, fec_alta DESC);
CREATE INDEX IF NOT EXISTS interaccion_con_incidentes_ix ON agente.interaccion (fec_alta DESC)
    WHERE incidentes <> '[]'::jsonb;

-- -----------------------------------------------------------------------------
-- 2. Tools llamadas, con lo que vio el modelo
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agente.tool_llamada (
    tool_llamada_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interaccion_id  uuid        NOT NULL REFERENCES agente.interaccion(interaccion_id) ON DELETE CASCADE,
    empr_id         integer     NOT NULL,
    orden           integer     NOT NULL,
    tool            text        NOT NULL,
    argumentos      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    status          text        NOT NULL,
    contenido       text,
    latencia_ms     integer,
    error           text,
    fec_alta        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tool_llamada_status_ck CHECK (status IN ('ok', 'error', 'bloqueada')),
    CONSTRAINT tool_llamada_orden_uk  UNIQUE (interaccion_id, orden)
);

COMMENT ON TABLE  agente.tool_llamada           IS 'Cada tool llamada en una corrida (R8). Insumo del guardian de cifras (R4).';
COMMENT ON COLUMN agente.tool_llamada.contenido IS 'Exactamente lo que se le paso al modelo como resultado de la tool (ya truncado). Una cifra de la respuesta tiene que salir de aca.';

CREATE INDEX IF NOT EXISTS tool_llamada_interaccion_ix ON agente.tool_llamada (interaccion_id);

-- -----------------------------------------------------------------------------
-- 3. RLS: un empr_id solo ve y escribe lo suyo. Sin contexto, nada.
-- -----------------------------------------------------------------------------
ALTER TABLE agente.interaccion  ENABLE ROW LEVEL SECURITY;
ALTER TABLE agente.interaccion  FORCE  ROW LEVEL SECURITY;
ALTER TABLE agente.feedback     ENABLE ROW LEVEL SECURITY;
ALTER TABLE agente.feedback     FORCE  ROW LEVEL SECURITY;
ALTER TABLE agente.tool_llamada ENABLE ROW LEVEL SECURITY;
ALTER TABLE agente.tool_llamada FORCE  ROW LEVEL SECURITY;

DROP POLICY IF EXISTS interaccion_aislamiento_empresa ON agente.interaccion;
CREATE POLICY interaccion_aislamiento_empresa ON agente.interaccion
    USING (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer)
    WITH CHECK (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer);

DROP POLICY IF EXISTS tool_llamada_aislamiento_empresa ON agente.tool_llamada;
CREATE POLICY tool_llamada_aislamiento_empresa ON agente.tool_llamada
    USING (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer)
    WITH CHECK (empr_id = NULLIF(current_setting('agente.empr_id', true), '')::integer);

-- feedback no tiene empr_id: es de la empresa de su interaccion. Como la
-- subconsulta tambien pasa por la policy de interaccion, una empresa no ve ni
-- califica la interaccion de otra.
DROP POLICY IF EXISTS feedback_aislamiento_empresa ON agente.feedback;
CREATE POLICY feedback_aislamiento_empresa ON agente.feedback
    USING (EXISTS (SELECT 1 FROM agente.interaccion i WHERE i.interaccion_id = feedback.interaccion_id))
    WITH CHECK (EXISTS (SELECT 1 FROM agente.interaccion i WHERE i.interaccion_id = feedback.interaccion_id));

-- La vista corre con los permisos de quien la consulta, no de su dueño: si no,
-- un dueño superusuario se saltea las policies y la vista mostraria todo.
ALTER VIEW agente.v_feedback_negativo SET (security_invoker = true);

-- El runtime inserta y lee; no corrige ni borra lo que hicieron las tools.
REVOKE ALL ON agente.tool_llamada FROM agente_app;
GRANT SELECT, INSERT ON agente.tool_llamada TO agente_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON agente.tool_llamada TO agente_curador;

INSERT INTO agente.schema_version (script, descripcion)
VALUES ('013-corrida', 'Corrida auditable (R8): agente, disparador, costo, controles, incidentes, tool_llamada; RLS en interaccion y feedback')
ON CONFLICT (script) DO UPDATE SET aplicado_en = now();
